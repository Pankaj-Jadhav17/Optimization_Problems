#include <time.h>

/* ── helpers ─────────────────────────────────── */
static void fill_random(unsigned char *buf, int len) {
    for (int i = 0; i < len; i++) buf[i] = rand() % 256;
}

/* ── init ─────────────────────────────────────── */
void init_sim(Sim *s, int n) {
    s->n = n; s->iter = 0;
    s->total_sent = s->total_collisions = 0;
    srand(time(NULL));
    for (int i = 0; i < n; i++) {
        s->hosts[i].id   = i;
        s->hosts[i].smac = SMAC(i);
        s->hosts[i].sent = s->hosts[i].received = s->hosts[i].busy = 0;
        memset(&s->hosts[i].tp_port,  0, sizeof(Port));
        memset(&s->hosts[i].lan_port, 0, sizeof(Port));
    }
    printf("Initialized %d hosts (SMAC: ", n);
    for (int i = 0; i < n; i++) printf("%c ", SMAC(i));
    printf(")\n");
}

/* ── STRIP: TestP for host i ─────────────────── */
/* Generates data ~10% of time. Prints received data. */
void strip_testp(Sim *s, int i) {
    Host *h = &s->hosts[i];

    /* Check in-buffer: if data arrived, print it */
    if (h->tp_port.d[1][0] > 0) {
        int bc = h->tp_port.d[1][0];
        printf("TestP%d received packet (%d bytes): ", i, bc);
        for (int j = 1; j <= bc && j <= 8; j++)
            printf("%d ", h->tp_port.d[1][j]);
        printf("\n");
        h->tp_port.d[1][0] = 0;   /* consume it */
        h->received++;
    }

    /* Generate packet ~10% of the time if out-buffer empty */
    if (h->tp_port.d[0][0] == 0 && PROB(10)) {
        /* pick a random destination (different host) */
        int dst = rand() % s->n;
        if (dst == i) dst = (i + 1) % s->n;

        int bc = 13 + rand() % 8;   /* 13 to 20 bytes */
        h->tp_port.d[0][0] = (unsigned char)bc;

        /* Packet: [src_id][src_smac][net][dst_id][dst_smac][bc][data...] */
        h->tp_port.d[0][1] = (unsigned char)i;
        h->tp_port.d[0][2] = (unsigned char)h->smac;
        h->tp_port.d[0][3] = (unsigned char)NET_ADDR;
        h->tp_port.d[0][4] = (unsigned char)dst;
        h->tp_port.d[0][5] = (unsigned char)SMAC(dst);
        fill_random(&h->tp_port.d[0][6], bc - 6);

        printf("Data generated by host %d for host %d\n", i, dst);
        printf("Packet = \"%d %c %d %d %c %d ...\"\n",
               i, h->smac, NET_ADDR, dst, SMAC(dst), bc);
        h->sent++;
        s->total_sent++;
    }
}

/* ── STRIP: LLL (Logical Link Layer) for host i ─ */
/* Passes data between TestP port and LAN port.    */
void strip_lll(Sim *s, int i) {
    Host *h = &s->hosts[i];

    /* TestP out → LAN out (forward to LAN) */
    if (h->tp_port.d[0][0] > 0 && h->lan_port.d[0][0] == 0) {
        printf("Connecting TP and LLL of %d\n", i);
        memcpy(h->lan_port.d[0], h->tp_port.d[0], BUF);
        printf("Copying LLL-in to LLL-out of %d\n", i);
        h->tp_port.d[0][0] = 0;
    }

    /* LAN in → TestP in (deliver received frame) */
    if (h->lan_port.d[1][0] > 0 && h->tp_port.d[1][0] == 0) {
        /* Check SMAC: byte[2] is dst SMAC */
        char dst_smac = (char)h->lan_port.d[1][5];
        if (dst_smac == h->smac) {
            memcpy(h->tp_port.d[1], h->lan_port.d[1], BUF);
        } else {
            printf("Host%d says: \"This packet is not for me! I drop it!\"\n", i);
        }
        h->lan_port.d[1][0] = 0;
    }
}

/* ── STRIP: LAN ──────────────────────────────── */
/* Collision detection: if >1 input port has data → collision.
   Otherwise broadcast to all output ports.       */
void strip_lan(Sim *s) {
    /* count how many hosts are sending */
    int active = 0, sender = -1;
    for (int i = 0; i < s->n; i++) {
        if (s->hosts[i].lan_port.d[0][0] > 0) {
            active++; sender = i;
        }
    }

    if (active == 0) return;   /* nothing to do */

    if (active > 1) {
        /* COLLISION: drop everything */
        printf("******* DATA LOST DUE TO COLLISION *******\n");
        for (int i = 0; i < s->n; i++)
            s->hosts[i].lan_port.d[0][0] = 0;
        s->total_collisions++;
        return;
    }

    /* One sender: broadcast to all other hosts' in-buffers */
    printf("******* Sending data over the LAN *******\n");
    printf("Receiver = %d\n", (int)s->hosts[sender].lan_port.d[0][4]);
    for (int i = 0; i < s->n; i++) {
        printf(" connecting LAN and LLL of %d\n", i);
        if (s->hosts[i].lan_port.d[1][0] == 0)
            memcpy(s->hosts[i].lan_port.d[1],
                   s->hosts[sender].lan_port.d[0], BUF);
    }
    printf("Copied packet to LLL of all hosts\n");
    s->hosts[sender].lan_port.d[0][0] = 0;   /* clear sender out-buf */
}

/* ── STRIP: Connectors ───────────────────────── */
/* Moves data from one port's out-buf to another's in-buf */
void connectors(Sim *s) {
    for (int i = 0; i < s->n; i++) {
        Host *h = &s->hosts[i];
        /* LLL out → LAN in */
        if (h->lan_port.d[0][0] > 0) {
            printf("Connecting LLL and LAN of %d\n", i);
            printf("Copying LAN-in to LAN-out of %d\n", i);
        }
    }
}

/* ── Scheduler: one full iteration ──────────────*/
void scheduler(Sim *s) {
    s->iter++;
    printf("------------------------------------------------------------------------\n");
    printf("ITERATION NO. : %d\n", s->iter);
    printf("--------------------\n");

    int any_data = 0;

    /* Run each TestP strip */
    for (int i = 0; i < s->n; i++) strip_testp(s, i);

    /* Run each LLL strip */
    for (int i = 0; i < s->n; i++) strip_lll(s, i);

    /* Check if anyone has data to send */
    for (int i = 0; i < s->n; i++)
        if (s->hosts[i].lan_port.d[0][0] > 0) any_data = 1;

    if (!any_data) {
        printf("No machine has any data to send\n");
        return;
    }

    /* Run connectors then LAN */
    connectors(s);
    strip_lan(s);

    /* Run LLL again to deliver received frames */
    for (int i = 0; i < s->n; i++) strip_lll(s, i);
}

/* ── Display ─────────────────────────────────── */
void show_hosts(Sim *s) {
    printf("\n+------+------+-------------+\n");
    printf("| Host | SMAC | SIP         |\n");
    printf("+------+------+-------------+\n");
    for (int i = 0; i < s->n; i++)
        printf("|  %d   |  %c   | (%d, %d)      |\n",
               i, s->hosts[i].smac, NET_ADDR, i);
    printf("+------+------+-------------+\n\n");
}

void show_stats(Sim *s) {
    printf("\n===== STATISTICS =====\n");
    printf("Iterations   : %d\n", s->iter);
    printf("Total Sent   : %d\n", s->total_sent);
    printf("Collisions   : %d\n", s->total_collisions);
    printf("\nHost  SMAC  Sent  Received\n");
    printf("--------------------------\n");
    for (int i = 0; i < s->n; i++)
        printf("  %d     %c    %d     %d\n",
               i, s->hosts[i].smac,
               s->hosts[i].sent, s->hosts[i].received);
    printf("======================\n\n");
}